package com.practice.java.code.samples.javafundmentals;

public class WhileLoop {
	
	//While Loop	When you don’t know how many times to loop.
	//While Loop	"Waiting for the bus (you don’t know how long it'll take)."
	

	public static void main(String[] args) {
		int i = 1;
		while (i <= 5) {
		    System.out.println(i);
		    i++;
		}

	}

}
