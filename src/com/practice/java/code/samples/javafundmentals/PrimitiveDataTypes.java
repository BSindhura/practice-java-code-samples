package com.practice.java.code.samples.javafundmentals;

public class PrimitiveDataTypes {

	public static void main(String[] args) {
		
		//Defines and stores a student's ID as an integer, 
		//score as a double, grade as a character, and 
		//active status as a boolean.
		
		int studentId = 101;
		double studentScore = 95.7;
		char grade = 'A';
		boolean isActive = true;
		
		System.out.println("Student ID: " +studentId );
		System.out.println("Student Score: " +studentScore);
		System.out.println("Grade: " +grade);
		System.out.println("Active Status: " +isActive);

	}

}
